// Рассчитываем предварительную стоимость проекта.
//
// В будущем сюда можно будет добавить
// намного больше вариантов.
function calculatePrice(options = {}) {

    // Базовая стоимость сайта.
    let price = 15000;

    // Если нужна галерея,
    // добавляем 1500 ₽.
    if (options.gallery) {
        price += 1500;
    }

    // Если нужна форма заявки,
    // добавляем 1000 ₽.
    if (options.form) {
        price += 1000;
    }

    // Если нужна карта,
    // добавляем 500 ₽.
    if (options.map) {
        price += 500;
    }

    // Если нужна онлайн-запись,
    // добавляем 3000 ₽.
    if (options.booking) {
        price += 3000;
    }

    // Возвращаем диапазон цены.
    return {
        priceFrom: price,
        priceTo: price + 5000,
    };
}

// Экспортируем функцию.
module.exports = {
    calculatePrice,
};